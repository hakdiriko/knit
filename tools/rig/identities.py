"""Writes Source/rig/Identities.cpp: who each of the plug-in's 11,705 neurons is in FlyWire.

The plug-in's cut (Source/dsp/FlyData.cpp) keeps only each neuron's place and wiring. This matches
every one of them back to FlyWire's 783 release by its place (FlyData stores it to 1/65535 of the
cut's box), then proves the match: the cut's whole wiring, rebuilt from the matched neurons out of
FlyWire's own connectivity, must equal FlyData's synapse for synapse. Only then is anything written.

usage: python3 tools/rig/identities.py DATA_DIR
DATA_DIR holds Completeness_783.csv and Connectivity_783.parquet (github.com/philshiu/Drosophila_brain_model)
and Supplemental_file1_neuron_annotations.tsv (github.com/flyconnectome/flywire_annotations, supplemental_files/).
Needs numpy, scipy, pandas, pyarrow."""
import os, re, sys
import numpy as np, pandas as pd, scipy.sparse as sp

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
D = sys.argv[1].rstrip('/') + '/'
WSYN = 0.275  # tools/fly/sim.py

def carray(src, name):
    m = re.search(r'\b' + name + r'\[\d+\] = \{(.*?)\};', src, re.S)
    return np.array([int(v) for v in m.group(1).replace('\n', ' ').split(',') if v.strip()], dtype=np.int64)

src = open(os.path.join(ROOT, 'Source', 'flies', 'flywire', 'FlyData.cpp')).read()
X, Y = carray(src, 'neuronX'), carray(src, 'neuronY')
rowStart, target, weight = carray(src, 'rowStart'), carray(src, 'target'), carray(src, 'weight')
N = len(X)
print('cut', N, 'neurons', len(target), 'connections')

comp = pd.read_csv(D + 'Completeness_783.csv', index_col=0)
ids = comp.index.values
con = pd.read_parquet(D + 'Connectivity_783.parquet')
W = sp.csr_matrix((con['Excitatory x Connectivity'].values.astype(np.float32) * WSYN,
                   (con['Presynaptic_Index'].values, con['Postsynaptic_Index'].values)), shape=(len(ids), len(ids)))
ann = pd.read_csv(D + 'Supplemental_file1_neuron_annotations.tsv', sep='\t', low_memory=False).set_index('root_id').reindex(ids)

# the places, exactly as tools/fly/export.py wrote them
px, py = ann.pos_x.values, ann.pos_y.values
x0, x1, y0, y1 = 22000.0, 226000.0, 12800.0, 111000.0
qx = np.rint(np.clip((np.nan_to_num(px, nan=124000) - x0) / (x1 - x0), 0, 1) * 65535).astype(np.int64)
qy = np.rint(np.clip((np.nan_to_num(py, nan=60000) - y0) / (y1 - y0), 0, 1) * 65535).astype(np.int64)
where = {}
for k, key in enumerate(qx * 65536 + qy):
    where.setdefault(int(key), []).append(k)

# each cut neuron's candidates; the cut keeps FlyWire's order, so walk them in order
keep = np.full(N, -1)
last = -1
for k in range(N):
    cands = [c for c in where.get(int(X[k] * 65536 + Y[k]), []) if c > last]
    if not cands:
        sys.exit('no FlyWire neuron at the place of cut neuron %d' % k)
    keep[k] = cands[0]
    last = keep[k]
amb = sum(1 for k in range(N) if len(where[int(X[k] * 65536 + Y[k])]) > 1)
print('matched by place; places shared with another neuron:', amb)

# the proof: the cut's wiring, rebuilt from FlyWire's, synapse for synapse
Wk = W[keep][:, keep].tocsr(); Wk.sort_indices()
counts = np.rint(Wk.data / WSYN).astype(np.int64)
same = np.array_equal(Wk.indptr, rowStart) and np.array_equal(Wk.indices, target) and np.array_equal(counts, weight)
print('wiring identical:', same)
if not same:
    sys.exit('the wiring does not match: nothing written')

def text(col):
    return [str(v) if isinstance(v, str) else '' for v in ann[col].values[keep]]
types, nts, classes, sides = text('cell_type'), text('top_nt'), text('super_class'), text('side')
for k in range(N):  # FlyWire leaves some unnamed: their hemibrain type, if any
    if not types[k]:
        h = ann['hemibrain_type'].values[keep[k]]
        types[k] = str(h) if isinstance(h, str) else ''
def table(values):
    names = sorted(set(values)); at = {v: i for i, v in enumerate(names)}
    return names, [at[v] for v in values]
typeNames, typeIx = table(types); ntNames, ntIx = table(nts); classNames, classIx = table(classes); sideNames, sideIx = table(sides)

def strings(name, vs):
    return 'const char* const %s[%d] = {\n%s\n};\n' % (name, len(vs), '\n'.join('    "%s",' % v.replace('"', '') for v in vs))
def ints(ctype, name, vs, per=12):
    rows = [', '.join(str(v) for v in vs[i:i + per]) for i in range(0, len(vs), per)]
    return 'const %s %s[%d] = {\n%s\n};\n' % (ctype, name, len(vs), '\n'.join('    ' + r + ',' for r in rows))

out = ['// Generated by tools/rig/identities.py from FlyWire 783 (Dorkenwald et al. 2024, Schlegel et al. 2024).',
       '// Do not edit. Each of the cut\'s neurons: its FlyWire root id, cell type, transmitter, class and side.',
       '// The match was proven by rebuilding the cut\'s wiring from FlyWire\'s connectivity: identical.',
       '#include "Identities.h"', '', 'namespace dendrite::rig::identities', '{',
       'static_assert (count == %d);' % N,
       ints('uint64_t', 'rootId', [int(ids[k]) for k in keep], 4),
       strings('typeName', typeNames), ints('uint16_t', 'type', typeIx),
       strings('transmitterName', ntNames), ints('uint8_t', 'transmitter', ntIx, 24),
       strings('className', classNames), ints('uint8_t', 'superClass', classIx, 24),
       strings('sideName', sideNames), ints('uint8_t', 'side', sideIx, 24),
       '} // namespace dendrite::rig::identities', '']
open(os.path.join(ROOT, 'Source', 'flies', 'flywire', 'Identities.cpp'), 'w').write('\n'.join(out))
print('written:', len(typeNames), 'types,', ntNames, classNames, sideNames)
print('unnamed:', sum(1 for t in types if not t))
